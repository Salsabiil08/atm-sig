const db=new PGlite()
const PIC='aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa'
const BOSS='bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb'
const SUPER='66666666-6666-4666-8666-666666666666'
const q=async sql=>(await db.query(sql)).rows[0]
const fail=async (sql,msg)=>assert.rejects(db.exec(sql),undefined,msg)
const schema=[
'CREATE ROLE anon','CREATE ROLE authenticated','CREATE SCHEMA auth',
"CREATE TYPE task_priority AS ENUM ('rendah','sedang','tinggi')",
"CREATE TYPE task_status AS ENUM ('To do','In progress','Blocked','Review','Revisi','Done')",
"CREATE TYPE org_unit_type AS ENUM ('department','unit','section')",
"CREATE TYPE support_status AS ENUM ('diminta','diberikan')",
'CREATE TABLE roles(id int PRIMARY KEY,level int NOT NULL)',
'CREATE TABLE org_units(id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,parent_id int REFERENCES org_units(id) ON DELETE RESTRICT,name text NOT NULL,type org_unit_type NOT NULL)',
"CREATE TABLE users(id uuid PRIMARY KEY,role_id int REFERENCES roles(id),org_unit_id int REFERENCES org_units(id),supervisor_id uuid,status text DEFAULT 'aktif')",
'CREATE TABLE task_categories(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),org_unit_id int REFERENCES org_units(id),is_active boolean DEFAULT true)',
"CREATE TABLE tasks(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),owner_id uuid REFERENCES users(id),assigner_id uuid REFERENCES users(id),reviewer_id uuid REFERENCES users(id),org_unit_id int REFERENCES org_units(id),parent_task_id uuid,title text,priority task_priority,start_date timestamptz,due_date timestamptz,category_id uuid,status task_status DEFAULT 'To do',progress_pct int DEFAULT 0,completed_at timestamptz)",
'CREATE TABLE evidence_requirements(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),task_id uuid REFERENCES tasks(id),description text,mandatory boolean)',
'CREATE TABLE wbs_items(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),task_id uuid REFERENCES tasks(id),parent_id uuid REFERENCES wbs_items(id),title text,weight numeric,is_done boolean)',
'CREATE TABLE task_supports(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),task_id uuid REFERENCES tasks(id),needed_from_id uuid REFERENCES users(id),description text,status support_status)',
'CREATE TABLE audit_logs(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),user_id uuid,action text,object text,old_value text,new_value text)',
"CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS 'SELECT nullif(current_setting(''app.user_id'',true),'''')::uuid'",
"CREATE FUNCTION get_my_role_level() RETURNS int LANGUAGE sql STABLE AS 'SELECT nullif(current_setting(''app.role_level'',true),'''')::int'",
"CREATE FUNCTION get_my_org_unit_id() RETURNS int LANGUAGE sql STABLE AS 'SELECT nullif(current_setting(''app.org_unit_id'',true),'''')::int'",
"CREATE FUNCTION can_access_task_scope(int,uuid,uuid) RETURNS boolean LANGUAGE sql STABLE AS 'SELECT get_my_role_level()>=2'",
"INSERT INTO roles VALUES(2,2),(3,3),(6,6)",
"INSERT INTO org_units(id,parent_id,name,type) VALUES(1,NULL,'Accounting','department'),(2,1,'Unit A','unit'),(3,2,'Section A','section')",
"SELECT setval(pg_get_serial_sequence('org_units','id'),3,true)",
"INSERT INTO users(id,role_id,org_unit_id,supervisor_id) VALUES('$PIC',2,3,'$BOSS'),('$BOSS',3,3,NULL),('$SUPER',6,1,NULL)",
'GRANT USAGE ON SCHEMA public,auth TO authenticated,anon',
'GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated',
'GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA public TO authenticated',
'GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA public,auth TO authenticated,anon',
'ALTER TABLE tasks ENABLE ROW LEVEL SECURITY',
'ALTER TABLE wbs_items ENABLE ROW LEVEL SECURITY',
'ALTER TABLE task_supports ENABLE ROW LEVEL SECURITY',
'ALTER TABLE evidence_requirements ENABLE ROW LEVEL SECURITY',
'ALTER TABLE org_units ENABLE ROW LEVEL SECURITY',
"CREATE POLICY org_read ON org_units FOR SELECT TO authenticated USING (true)",
"CREATE POLICY org_write ON org_units FOR ALL TO authenticated USING (get_my_role_level()=6) WITH CHECK (get_my_role_level()=6)",
"CREATE POLICY task_read ON tasks FOR SELECT TO authenticated USING (get_my_role_level()>=2)",
"CREATE POLICY task_insert ON tasks FOR INSERT TO authenticated WITH CHECK ((get_my_role_level()=2 AND owner_id=auth.uid() AND assigner_id=auth.uid() AND org_unit_id=get_my_org_unit_id()) OR get_my_role_level()>=3)",
"CREATE POLICY task_update ON tasks FOR UPDATE TO authenticated USING (get_my_role_level()>=2) WITH CHECK (get_my_role_level()>=2)",
"CREATE POLICY wbs_read ON wbs_items FOR SELECT TO authenticated USING (true)",
"CREATE POLICY wbs_insert ON wbs_items FOR INSERT TO authenticated WITH CHECK (get_my_role_level()>=2)",
"CREATE POLICY evidence_insert ON evidence_requirements FOR INSERT TO authenticated WITH CHECK (get_my_role_level()>=2)",
"CREATE POLICY support_insert ON task_supports FOR INSERT TO authenticated WITH CHECK (get_my_role_level()>=2)",
"CREATE POLICY support_read ON task_supports FOR SELECT TO authenticated USING (true)",
].join(';\n')+';'
try {
  await db.exec(schema.replaceAll('$PIC',PIC).replaceAll('$BOSS',BOSS).replaceAll('$SUPER',SUPER))
  await db.exec(readFileSync(new URL('../supabase/migrations/20261024202000_r03_task_bundle_and_org_guard.sql',import.meta.url),'utf8'))
  await db.exec(readFileSync(new URL('../supabase/migrations/20261024203000_r03_task_state_event_history.sql',import.meta.url),'utf8'))
  assert.equal((await q("SELECT has_function_privilege('anon','public.create_task_bundle_r03(uuid,uuid,integer,uuid,text,public.task_priority,timestamptz,timestamptz,uuid,jsonb,jsonb,jsonb)','EXECUTE') AS ok")).ok,false)
  await db.exec("SET app.user_id='"+PIC+"'; SET app.role_level='2'; SET app.org_unit_id='3'; SET ROLE authenticated")
  const call=(wbs,support)=>"SELECT create_task_bundle_r03('"+PIC+"','"+BOSS+"',3,NULL,'Closing','sedang','2026-10-01','2026-10-31',NULL,'[]'::jsonb,'"+JSON.stringify(wbs)+"'::jsonb,'"+JSON.stringify(support)+"'::jsonb)"
  const good=[{title:'Root',weight:0,parentIndex:null},{title:'Reconcile',weight:60,parentIndex:0},{title:'Review',weight:40,parentIndex:0}]
  await db.exec(call(good,[{neededFromId:BOSS,description:'Ledger'}]))
  assert.equal((await q('SELECT count(*)::int n FROM tasks')).n,1)
  assert.equal((await q('SELECT count(*)::int n FROM wbs_items')).n,3)
  assert.equal((await q('SELECT count(*)::int n FROM task_supports')).n,1)
  assert.equal((await q('SELECT count(*)::int n FROM task_state_events')).n,1,'task creation writes lifecycle event')
  await fail(call([{title:'Wrong weight',weight:90,parentIndex:null}],[]),'rollback bad weight')
  await fail(call(good,[{neededFromId:PIC,description:'Self'}]),'rollback bad support')
  await fail(call([{title:'Bad parent',weight:100,parentIndex:7}],[]),'rollback bad parent')
  assert.equal((await q('SELECT count(*)::int n FROM tasks')).n,1,'no partial tasks after invalid input')
  await db.exec('RESET ROLE')
  await db.exec("SET app.user_id='"+SUPER+"'; SET app.role_level='6'; SET app.org_unit_id='1'; SET ROLE authenticated")
  await fail("INSERT INTO org_units(name,type,parent_id) VALUES('Bad Section','section',1)",'wrong org hierarchy')
  await db.exec("INSERT INTO org_units(name,type,parent_id) VALUES('New Unit','unit',1)")
  assert.equal((await q("SELECT count(*)::int n FROM audit_logs WHERE action='org_insert'")).n,1)
  await fail("UPDATE org_units SET parent_id=3 WHERE id=2",'unit cannot become child of section')
  assert.equal((await q('SELECT parent_id FROM org_units WHERE id=2')).parent_id,1)
  console.log('PASS isolated R.03 migration, atomic rollback, WBS hierarchy and org audit')
} catch(e) {
  console.error(e)
  process.exitCode=1
} finally {
  await db.close()
}
